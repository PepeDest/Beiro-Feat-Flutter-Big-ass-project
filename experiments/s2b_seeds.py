"""S2b over 7 draws of units (seeds 2026-2032). Rules: docs/S2.md, section "S2b with 5 more draws of units".
Reads results/e6b_summary.json (seed 2026) and e6b_summary_seed{S}.json for S = 2027..2032. No simulation."""
import json
import numpy as np
from common import RES, save_json

FILES = [("2026", "e6b_summary.json")] + [(str(s), f"e6b_summary_seed{s}.json") for s in range(2027, 2033)]
D = {s: json.loads((RES / f).read_text()) for s, f in FILES if (RES / f).exists()}
rows = {s: dict(G=d["results"], v=d["verdicts"], tau=d.get("tau_star")) for s, d in D.items()}
ref = rows["2026"]["v"]
q4 = {k: all(r["v"][k] == ref[k] for r in rows.values()) for k in ("G0", "G1", "G3", "G4")}
n_gate = sum(r["v"]["Gate"].startswith("triggered") for r in rows.values()); n = len(rows)
q2 = ("robust" if n_gate >= 6 else "not robust" if n_gate <= 3 else "mixed") if n == 7 else f"not computed ({n} of 7 draws)"
auc = np.array([r["G"]["G2"][0] for r in rows.values()]); rng = np.random.default_rng(0)
bs = [auc[rng.integers(0, n, n)].mean() for _ in range(10000)]; lo, hi = np.percentile(bs, [2.5, 97.5])
q3 = "C mislabels rocks" if lo > 0.5 else "C favours oscillators" if hi < 0.5 else "no difference"
v = dict(Q2=q2, n_gate=n_gate, n_draws=n, Q3=q3, Q3_value=[float(auc.mean()), float(lo), float(hi)], Q4="yes" if all(q4.values()) else f"no ({q4})")
save_json("s2b_seeds.json", dict(per_draw={s: dict(G2=r["G"]["G2"], verdicts=r["v"], tau_star=r["tau"]) for s, r in rows.items()}, verdicts=v))
f = lambda x: f"{x[0]:+.2f} [{x[1]:+.2f}, {x[2]:+.2f}]"
L = ["# S2b over draws of units (auto-generated by experiments/s2b_seeds.py; rules in docs/S2.md)\n",
     "| Seed | τ* | G0 | G1 | G2: AUC of C(τ*) | G3 | G4 | Gate |", "|---|---|---|---|---|---|---|---|"]
L += [f"| {s} | {r['tau'] or float('nan'):.1f} | {r['v']['G0']} | {r['v']['G1']} | {f(r['G']['G2'])} {r['v']['G2']} | {r['v']['G3']} | {r['v']['G4']} | {r['v']['Gate']} |" for s, r in rows.items()]
L += ["", f"- Q2 (gate): {q2} (triggered in {n_gate} of {n} draws)", f"- Q3 (pooled G2): {f(v['Q3_value'])}: {q3}", f"- Q4 (G0, G1, G3, G4 in every draw): {v['Q4']}"]
(RES / "s2b_seeds.md").write_text("\n".join(L) + "\n", encoding="utf-8"); print("\n".join(L))
