"""S1 - apply the fixed verdict rules of docs/S1.md to every setting and write results/s1_table.md.
Reads results/e3_summary{tag}.json and results/e4_merging{tag}.json. No simulation."""
import json
from common import RES

SETTINGS = [("", "baseline (tau 1, p_out 0.05, N 6)"), ("_tau0.5", "tau 0.5"), ("_tau2", "tau 2"),
            ("_p0.01", "p_out 0.01"), ("_p0.2", "p_out 0.2"), ("_N5", "N 5"), ("_N7", "N 7"),
            ("_D2", "D-test r 2"), ("_D3", "D-test r 3")]
FAMS = ("equilibrium", "driven", "modular_driven")
PHI = "Phi_orig(b=1,l=.25)"


def h1(e3):
    pt, lo, hi = e3["all"]["spearman"][PHI]
    v = "supported" if lo > 0 else "not supported"
    return v, f"{pt:+.2f} [{lo:+.2f}, {hi:+.2f}]"


def h2(e3):
    want = {"P": +1, "C": +1, "KH": -1}
    point_ok, ci_ok, wrong = True, True, []
    for fam in FAMS:
        r = e3[fam]
        for name, sign in want.items():
            i = r["coef_names"].index(name)
            c, lo, hi = r["coef"][i], r["coef_lo"][i], r["coef_hi"][i]
            if c * sign <= 0:
                point_ok = False; wrong.append(f"{name}@{fam}")
            if lo <= 0 <= hi:
                ci_ok = False
    v = "supported" if point_ok and ci_ok else ("partial" if point_ok else "not supported")
    return v, ("wrong sign: " + ", ".join(wrong)) if wrong else ("all CIs exclude 0" if ci_ok else "some CI includes 0")


def h3(e3):
    m = e3["equilibrium"]["logR_mean"]
    v = "supported" if abs(m) < 0.05 else "not supported"
    return v, f"eq {m:+.3f}, driven {e3['driven']['logR_mean']:+.3f}, modular {e3['modular_driven']['logR_mean']:+.3f}"


def h4(e4):
    d, s = e4["all"]["dPhi_orig"], e4["all"]["static MI I(A;B)"]
    v = "supported" if d["rho"] > s["rho"] and d["lo"] > 0 else "not supported"
    return v, f"dPhi {d['rho']:+.2f}, I(A;B) {s['rho']:+.2f}"


rows, gate = [], []
for tag, label in SETTINGS:
    try:
        e3 = json.loads((RES / f"e3_summary{tag}.json").read_text())
        e4 = json.loads((RES / f"e4_merging{tag}.json").read_text())
    except FileNotFoundError as err:
        rows.append(f"| {label} | not run yet ({err.filename.split(chr(92))[-1].split('/')[-1]}) | | | | |"); continue
    v1, v2, v3, v4 = h1(e3), h2(e3), h3(e3), h4(e4)
    c = e3["all"]["spearman_within_size"]["C only"]; kh = e3["all"]["spearman_within_size"]["-KH (simplicity)"]
    if v1[0] == "supported":
        gate.append(label)
    rows.append(f"| {label} | {v1[0]}: {v1[1]} | {v2[0]} ({v2[1]}) | {v3[0]}: {v3[1]} | {v4[0]}: {v4[1]} | {c[0]:+.2f} [{c[1]:+.2f}, {c[2]:+.2f}] | {kh[0]:+.2f} [{kh[1]:+.2f}, {kh[2]:+.2f}] |")

L = ["# S1 verdict table (auto-generated by experiments/s1_summary.py; rules in docs/S1.md)\n",
     "| setting | H1: rho(Phi, log V) [95% CI] | H2: signs +P +C -KH | H3 control: mean log R | H4: rho with log S | C only, equal size | -K_H, equal size |",
     "|---|---|---|---|---|---|---|"] + rows
L.append("\nGate: H1 supported in " + (", ".join(gate) if gate else "no setting") + ".")
(RES / "s1_table.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("\n".join(L))
