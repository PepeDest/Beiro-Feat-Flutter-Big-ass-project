"""S3b - lagged good-regulator measure for R4 on the stored S3 organisms. Rules: docs/S3.md, section S3b. No simulation."""
import argparse, pickle
import numpy as np
from scipy.linalg import expm
from scipy.stats import spearmanr, rankdata
from common import RES, save_json
from vlife.agency import Organism, homeostat, H, V
from vlife.gaussian import mutual_information

LAGS = np.arange(0, 20.0001, 0.25)
ap = argparse.ArgumentParser(); ap.add_argument("--tag", default=""); TAG = ap.parse_args().tag
rows = [r for r in pickle.load(open(RES / f"e5_dataset{TAG}.pkl", "rb"))
        if min(r[v]["ev"] for v in ("intact", "scrambled", "nofeedback")) >= 5]


def lag_info(B, S):
    out = []
    for d in LAGS:
        cvh = (expm(-B * d) @ S)[V, H]                      # Cov(v_{t+d}, h_t)
        r2 = cvh ** 2 / (S[V, V] * S[H, H])
        out.append(-0.5 * np.log(1 - r2))
    return max(out)


def tau_v(B, S):
    t = (np.linalg.solve(B, S))[V, V] / S[V, V]            # integral of e^{-B d} S over d >= 0 is B^{-1} S
    if t > 0:
        return t, False
    grid = np.arange(0, 50.0001, 0.05)
    corr = [abs((expm(-B * d) @ S)[V, V] / S[V, V]) for d in grid]
    return float(np.trapezoid(corr, grid)), True


m = dict(Ilag_int=[], Ilag_nf=[], Ieq=[], tau=[], margin=[], logV=[]); fallback = 0; maxdiff = 0.0
for r in rows:
    o = Organism(**r["org"])
    Bi, _, Si = homeostat(o, "intact"); Bn, _, Sn = homeostat(o, "nofeedback")
    Ieq = mutual_information(Si, [V], [H]); maxdiff = max(maxdiff, abs(Ieq - r["intact"]["Ivh"]))
    t, fb = tau_v(Bi, Si); fallback += fb
    m["Ilag_int"].append(lag_info(Bi, Si)); m["Ilag_nf"].append(lag_info(Bn, Sn)); m["Ieq"].append(Ieq)
    m["tau"].append(t); m["margin"].append(r["c"] / np.sqrt(Si[V, V])); m["logV"].append(np.log(r["intact"]["V"]))
m = {k: np.array(v) for k, v in m.items()}
assert maxdiff < 1e-9, f"rebuild check failed: {maxdiff}"

n = len(rows); rng = np.random.default_rng(0)


def boot(fn):
    pt = fn(np.arange(n)); bs = [fn(rng.integers(0, n, n)) for _ in range(1000)]
    lo, hi = np.nanpercentile(bs, [2.5, 97.5]); return [float(pt), float(lo), float(hi)]


def partial(x, y, Z):
    def f(ids):
        rx, ry = rankdata(x[ids]), rankdata(y[ids])
        Zr = np.column_stack([np.ones(len(ids))] + [rankdata(z[ids]) for z in Z])
        res = lambda a: a - Zr @ np.linalg.lstsq(Zr, a, rcond=None)[0]
        return np.corrcoef(res(rx), res(ry))[0, 1]
    return f


rho = lambda a, b: (lambda ids: spearmanr(a[ids], b[ids])[0])
dI = m["Ilag_nf"] - m["Ilag_int"]
res = dict(n=n, rebuild_max_diff=maxdiff, tau_fallback_count=int(fallback),
           R4a=boot(rho(m["Ilag_int"], m["logV"])), R4b=boot(rho(dI, m["logV"])),
           R4c=boot(partial(m["Ieq"], m["logV"], [np.log(m["margin"]), np.log(m["tau"])])),
           raw_Ieq=boot(rho(m["Ieq"], m["logV"])),
           desc_rho_logtau_logV=boot(rho(np.log(m["tau"]), m["logV"])),
           desc_rho_logmargin_logV=boot(rho(np.log(m["margin"]), m["logV"])),
           desc_rho_Ieq_logtau=boot(rho(m["Ieq"], np.log(m["tau"]))),
           desc_frac_lag_gt_eq=float(np.mean(m["Ilag_int"] > m["Ieq"] + 1e-12)))
v = dict(R4a="present" if res["R4a"][2] < 0 else "not present",
         R4b="present" if res["R4b"][1] > 0 else "not present",
         R4c="explained" if res["R4c"][1] <= 0 else "not explained")
save_json(f"e5b_lag{TAG}.json", dict(results=res, verdicts=v))
f = lambda x: f"{x[0]:+.3f} [{x[1]:+.3f}, {x[2]:+.3f}]"
L = ["# S3b lag test (auto-generated by experiments/e5b_lag.py; rules in docs/S3.md)\n",
     f"Organisms: {n}. Rebuild check max |diff| = {maxdiff:.1e}. tau_v fallback used: {fallback}.\n",
     "| Rule | Value [95% CI] | Verdict |", "|---|---|---|",
     f"| R4a: rho(I_lag intact, log V) | {f(res['R4a'])} | {v['R4a']} |",
     f"| R4b: rho(I_lag nofeedback - I_lag intact, log V) | {f(res['R4b'])} | {v['R4b']} |",
     f"| R4c: partial rho(I(v;h), log V given margin, tau_v) | {f(res['R4c'])} (raw {f(res['raw_Ieq'])}) | {v['R4c']} |",
     "\nDescription only:",
     f"- rho(log tau_v, log V) {f(res['desc_rho_logtau_logV'])}; rho(log margin, log V) {f(res['desc_rho_logmargin_logV'])}",
     f"- rho(I(v;h), log tau_v) {f(res['desc_rho_Ieq_logtau'])}; I_lag > I(v_t;h_t) in {res['desc_frac_lag_gt_eq']:.0%} of organisms"]
(RES / f"e5b_lag{TAG}.md").write_text("\n".join(L) + "\n", encoding="utf-8"); print("\n".join(L))
