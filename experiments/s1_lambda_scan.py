"""S1 post-hoc check (written AFTER the tau results were seen; see docs/S1.md).
Idea: tau rescales the information terms (P, C) but not K_H, so a fixed lambda changes the real C : K_H balance.
Scan: mean within-world Spearman rho of Phi = P + C - lambda*K_H with log V, for each tau dataset. Point estimates only."""
import argparse, pickle
import numpy as np
from scipy.stats import spearmanr
from common import RES

LAMS = (0.0, 0.05, 0.1, 0.25, 0.5, 1.0)
rows = []
ap = argparse.ArgumentParser(); ap.add_argument("--suffix", default=""); SUF = ap.parse_args().suffix   # _v2: phase C data
for tag, tau in (("_tau0.5", 0.5), ("", 1.0), ("_tau2", 2.0)):
    data = pickle.load(open(RES / f"e3_dataset{tag}{SUF}.pkl", "rb"))
    line = []
    for lam in LAMS:
        r_all, r_size = [], []
        for d in data:
            m = (d["ev_on"] >= 5) & (d["ev_eq"] >= 5)
            if m.sum() < 8:
                continue
            f = {k: d["feat"][k][m] for k in ("P", "C", "KH", "size")}
            y = np.log(d["V_on"][m]); phi = f["P"] + f["C"] - lam * f["KH"]
            r_all.append(spearmanr(phi, y)[0])
            rs = [spearmanr(phi[f["size"] == k], y[f["size"] == k])[0] for k in np.unique(f["size"]) if (f["size"] == k).sum() >= 6]
            r_size.append(np.nanmean(rs))
        line.append(f"{np.mean(r_all):+.2f} / {np.nanmean(r_size):+.2f}")
    sdC = np.std(np.concatenate([d["feat"]["C"] - d["feat"]["C"].mean() for d in data]))
    rows.append(f"| {tau} | {sdC:.3f} | " + " | ".join(line) + " |")
L = ["# S1 post-hoc lambda scan (auto-generated by experiments/s1_lambda_scan.py)\n",
     "Each cell: mean within-world rho(Phi, log V), all structures / equal-size structures. beta = 1. Point estimates, no CI.\n",
     "| tau | sd(C) within world | " + " | ".join(f"lambda {l}" for l in LAMS) + " |",
     "|---|---|" + "---|" * len(LAMS)] + rows
(RES / f"s1_lambda_scan{SUF}.md").write_text("\n".join(L) + "\n", encoding="utf-8"); print("\n".join(L))
