"""C1 - control of the Brownian-bridge correction (fix #1) in E3 worlds. Rules: docs/RERUN.md (phase C).
For a subset of E3 worlds (same seeds as E3), the driven dynamics only, all 62 structures, 600 trajectories, t_max 200:
  a) dt = 0.05 with the bridge (the setting of the E3 rerun)
  b) dt = 0.005 with the bridge
  c) dt = 0.05 without the bridge (old method)
  d) dt = 0.005 without the bridge
  e) extrapolation to dt -> 0 from c) and d), linear in sqrt(dt) (the boundary shift grows like sqrt(dt))
Each run has its own random numbers. Monte Carlo error of log V per structure: about 1/sqrt(number of exits)."""
import argparse, time
import numpy as np
from scipy.stats import spearmanr
from common import RES, save_json
from vlife.worlds import make_world, FAMILIES
from vlife.functional import all_subsets, structure_features
from vlife.viability import simulate_exits, mfpt_all

RUNS = {"a": (0.05, True), "b": (0.005, True), "c": (0.05, False), "d": (0.005, False)}
K_EXT = np.sqrt(0.005) / (np.sqrt(0.05) - np.sqrt(0.005))


def world_job(job):
    fam, k, seed, n_traj, t_max = job
    rng = np.random.default_rng([seed, FAMILIES.index(fam), k])
    w = make_world(fam, 6, rng); subs = all_subsets(6)
    C = structure_features(w, 1.0, subs)["C"]; size = np.array([len(s) for s in subs])
    out = dict(family=fam, k=k, C=C, size=size)
    for j, (name, (dt, br)) in enumerate(RUNS.items()):
        V, ev, _ = mfpt_all(simulate_exits(w.B, w.S, subs, 0.05, n_traj, dt, t_max, np.random.default_rng([seed, FAMILIES.index(fam), k, 20 + j]), br))
        out[name] = (np.log(V), ev)
    return out


def compare(r, x, y, mask):
    lx, ly = r[x][0], (r[y][0] if y != "e" else r["d"][0] - (r["c"][0] - r["d"][0]) * K_EXT)
    with np.errstate(divide="ignore"):
      if y == "e":
        se2 = 1 / r["d"][1] + (K_EXT ** 2) * (1 / r["c"][1] + 1 / r["d"][1]) + 2 * K_EXT / r["d"][1]   # var of d - k (c - d)
      else:
        se2 = 1 / r[y][1]
    with np.errstate(divide="ignore"):
        se2 = se2 + 1 / r[x][1]
    diff = (lx - ly)[mask]; z = diff / np.sqrt(se2[mask])
    return float(diff.mean()), float(np.std(z)), float(spearmanr(lx[mask], ly[mask])[0])


def boot(v, n=1000, rng=np.random.default_rng(0)):
    v = np.asarray(v); bs = [v[rng.integers(0, len(v), len(v))].mean() for _ in range(n)]
    lo, hi = np.percentile(bs, [2.5, 97.5]); return [float(v.mean()), float(lo), float(hi)]


def rho_c(r, name, mask):
    y, s, C = r[name][0], r["size"], r["C"]
    rs = [spearmanr(C[mask & (s == q)], y[mask & (s == q)])[0] for q in np.unique(s) if (mask & (s == q)).sum() >= 6]
    return float(np.nanmean(rs))


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--per_family", type=int, default=4); ap.add_argument("--workers", type=int, default=2)
    ap.add_argument("--n_traj", type=int, default=600); ap.add_argument("--t_max", type=float, default=200.0)
    a = ap.parse_args(); t0 = time.time()
    from concurrent.futures import ProcessPoolExecutor
    jobs = [(fam, k, 2026, a.n_traj, a.t_max) for fam in FAMILIES for k in range(a.per_family)]
    with ProcessPoolExecutor(a.workers) as ex:
        rows = list(ex.map(world_job, jobs))
    print(f"simulation done in {time.time() - t0:.0f} s", flush=True)
    pairs = {"K1: a - b (bridge 0.05 - bridge 0.005)": ("a", "b"), "K2: a - e (bridge 0.05 - extrapolation)": ("a", "e"),
             "K3: a - d (bridge 0.05 - no bridge 0.005)": ("a", "d"), "old: c - e (no bridge 0.05 - extrapolation)": ("c", "e")}
    res = {}
    for label, (x, y) in pairs.items():
        per = [compare(r, x, y, np.min([r[n][1] for n in RUNS], 0) >= 5) for r in rows]
        res[label] = dict(mean_diff=boot([p[0] for p in per]), sd_z=float(np.mean([p[1] for p in per])),
                          rho_logV=float(np.mean([p[2] for p in per])))
    masks = [np.min([r[n][1] for n in RUNS], 0) >= 5 for r in rows]
    res["rho_C_logV_equal_size"] = {n: boot([rho_c(r, n, m) for r, m in zip(rows, masks)]) for n in RUNS}
    v = {}
    for key, lim in (("K1", 0.03), ("K2", 0.05), ("K3", 0.03)):
        lab = next(l for l in res if l.startswith(key)); m = res[lab]
        v[key] = "agree" if abs(m["mean_diff"][0]) < lim and m["sd_z"] < 1.5 else "do not agree"
    save_json("c1_dt_control.json", dict(settings=vars(a), n_worlds=len(rows), results=res, verdicts=v))
    f = lambda x: f"{x[0]:+.3f} [{x[1]:+.3f}, {x[2]:+.3f}]"
    L = ["# C1 dt control (auto-generated by experiments/c1_dt_control.py; rules in docs/RERUN.md)\n",
         f"Worlds: {len(rows)} ({a.per_family} per family), driven dynamics, 62 structures, n_traj {a.n_traj}, t_max {a.t_max}. "
         f"Time {time.time() - t0:.0f} s.\n",
         "| Comparison | mean difference of log V [95% CI over worlds] | sd of z | mean Spearman of log V | Verdict |", "|---|---|---|---|---|"]
    for lab, m in res.items():
        if lab.startswith(("K", "old")):
            L.append(f"| {lab} | {f(m['mean_diff'])} | {m['sd_z']:.2f} | {m['rho_logV']:.3f} | {v.get(lab[:2], 'description')} |")
    L += ["", "rho(C, log V) among structures of equal size, mean over worlds:", ""]
    L += [f"- {n} (dt {RUNS[n][0]}, bridge {RUNS[n][1]}): {f(x)}" for n, x in res["rho_C_logV_equal_size"].items()]
    (RES / "c1_dt_control.md").write_text("\n".join(L) + "\n", encoding="utf-8"); print("\n".join(L))
