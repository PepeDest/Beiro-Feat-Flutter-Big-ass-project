"""D1 - KSG at high mutual information in 4 dimensions (code review item 6). Rules: docs/RERUN.md, section D.

E1 validated KSG only up to 0.22 nats in 1-3 dimensions; S2 uses it on z = (x, v) pairs, I(z_t; z_t+tau), up to 2.7 nats.
Test pairs: X = (x1, x2), Y = (y1, y2) jointly Gaussian with exact I(X;Y) = target (two independent channels with
correlation rho each: I = -log(1 - rho^2) in total). Two geometries with the SAME exact MI:
  gauss: the Gaussian pairs as they are;
  ring:  each 2-vector u is mapped by the invertible map u -> (r cos th, r sin th), r = exp(0.3 u1), th = 2 atan(u2),
         th in (-pi, pi). MI is invariant under invertible maps of X and of Y separately [CoverThomas06, Kraskov04],
         so the exact value does not change, but the points lie on curved, ring-like sets, as the S2 oscillator states do.
n = 4000 pairs (as E6/E6b) and n = 16000; k = 4; 20 repetitions."""
import time
import numpy as np
from common import RES, save_json
from vlife.estimators import ksg_mi

TARGETS = (0.5, 1.0, 2.0, 2.7, 3.5)
NS, REPS, K = (4000, 16000), 20, 4


def pairs(target, n, rng):
    rho = np.sqrt(1 - np.exp(-target))                # per channel I = -0.5 log(1 - rho^2) = target / 2
    a = rng.normal(size=(n, 2)); b = rho * a + np.sqrt(1 - rho ** 2) * rng.normal(size=(n, 2))
    return a, b


def ring(u):
    r = np.exp(0.3 * u[:, 0]); th = 2 * np.arctan(u[:, 1])
    return np.column_stack([r * np.cos(th), r * np.sin(th)])


if __name__ == "__main__":
    t0 = time.time(); rng = np.random.default_rng(2026); rows = []
    for n in NS:
        for target in TARGETS:
            est = {"gauss": [], "ring": []}
            for _ in range(REPS):
                a, b = pairs(target, n, rng)
                est["gauss"].append(ksg_mi(a, b, K)); est["ring"].append(ksg_mi(ring(a), ring(b), K))
            row = dict(n=n, exact=target)
            for g, v in est.items():
                v = np.array(v); row[g] = dict(mean=float(v.mean()), sd=float(v.std()), bias=float(v.mean() - target),
                                              rel_bias=float((v.mean() - target) / target))
            rows.append(row); print(row, flush=True)
    worst = {g: max(abs(r[g]["bias"]) for r in rows if r["n"] == 4000 and 2.0 <= r["exact"] <= 3.0) for g in ("gauss", "ring")}
    worst_rel = {g: max(abs(r[g]["rel_bias"]) for r in rows if r["n"] == 4000 and 2.0 <= r["exact"] <= 3.0) for g in ("gauss", "ring")}
    large = any(worst[g] > 0.2 or worst_rel[g] > 0.10 for g in worst)
    v = dict(D1="KSG wrong by a lot" if large else "KSG adequate", worst_abs_bias_n4000_2to3nats=worst,
             worst_rel_bias_n4000_2to3nats=worst_rel)
    save_json("d1_ksg_highmi.json", dict(rows=rows, verdict=v, k=K, reps=REPS))
    L = ["# D1 KSG at high MI in 4 dimensions (auto-generated by experiments/d1_ksg_highmi.py; rules in docs/RERUN.md)\n",
         f"k = {K}, {REPS} repetitions. Time {time.time() - t0:.0f} s.\n",
         "| n | exact MI | gauss: mean (bias) | ring: mean (bias) |", "|---|---|---|---|"]
    L += [f"| {r['n']} | {r['exact']:.2f} | {r['gauss']['mean']:.3f} ({r['gauss']['bias']:+.3f}) | {r['ring']['mean']:.3f} ({r['ring']['bias']:+.3f}) |" for r in rows]
    L += ["", f"Verdict D1: {v['D1']} (largest |bias| at n = 4000, MI 2-3 nats: gauss {worst['gauss']:.3f}, ring {worst['ring']:.3f}; "
          f"relative: gauss {worst_rel['gauss']:.1%}, ring {worst_rel['ring']:.1%})"]
    (RES / "d1_ksg_highmi.md").write_text("\n".join(L) + "\n", encoding="utf-8"); print("\n".join(L))
