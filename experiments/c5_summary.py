"""C5 rules W1-W8 and list item 5 (share of the D-test shift and of the S3 VoI from the dt bias). Rules: docs/RERUN.md
(sections C5 and P5). Reads the e3/e4/e5 summary json files only; settings without a `_v2` file are reported as missing."""
import json
from common import RES, save_json

SET = [("", "baseline"), ("_tau0.5", "tau 0.5"), ("_tau2", "tau 2"), ("_p0.01", "p_out 0.01"), ("_p0.2", "p_out 0.2"),
       ("_N5", "N 5"), ("_N7", "N 7"), ("_D2", "D-test r 2"), ("_D3", "D-test r 3")]
PHI, KH, C = "Phi_orig(b=1,l=.25)", "-KH (simplicity)", "C only"
load = lambda name: json.loads((RES / name).read_text()) if (RES / name).exists() else None


def label(s):
    return ("mostly from the dt bias" if s > 0.5 else "partly from the dt bias" if s >= 0.2 else
            "little from the dt bias" if s >= -0.2 else "the dt bias hid part of the effect")


rows, missing = {}, []
for tag, lab in SET:
    o, n, e4n = load(f"e3_summary{tag}.json"), load(f"e3_summary{tag}_v2.json"), load(f"e4_merging{tag}_v2.json")
    if n is None or e4n is None:
        missing.append(lab); continue
    rows[lab] = dict(
        H1_old=o["all"]["spearman"][PHI][0], H1_new=n["all"]["spearman"][PHI],
        C_eq_old=o["all"]["spearman_within_size"][C][0], C_eq_new=n["all"]["spearman_within_size"][C],
        KH_eq_old=o["all"]["spearman_within_size"][KH][0], KH_eq_new=n["all"]["spearman_within_size"][KH][0],
        logR_eq_new=n["equilibrium"]["logR_mean"], logR_dr_old=o["driven"]["logR_mean"], logR_dr_new=n["driven"]["logR_mean"],
        H4_supported=e4n["all"]["dPhi_orig"]["rho"] > e4n["all"]["static MI I(A;B)"]["rho"] and e4n["all"]["dPhi_orig"]["lo"] > 0)
v = {}
if not missing:
    v["W1"] = "stands" if all(r["C_eq_new"][1] > 0 for r in rows.values()) else "does not stand"
    v["W2"] = "stands" if not any(r["H4_supported"] for r in rows.values()) else "does not stand"
    v["W3"] = "exact" if all(abs(r["logR_eq_new"]) < 1e-9 for r in rows.values()) else "not exact"
    v["W4"] = [lab for lab, r in rows.items() if r["H1_new"][1] > 0]
    b, d2, d3 = rows["baseline"]["KH_eq_new"], rows["D-test r 2"]["KH_eq_new"], rows["D-test r 3"]["KH_eq_new"]
    v["W5"] = "supported" if (d3 - b) > 0.2 and min(b, d3) <= d2 <= max(b, d3) else "not supported"
    P5 = {}
    for lab in ("D-test r 2", "D-test r 3"):
        r, base = rows[lab], rows["baseline"]
        for name, key_old, key_new in (("K_H shift", "KH_eq_old", "KH_eq_new"), ("H1 shift", "H1_old", "H1_new")):
            old = r[key_old] - base[key_old]
            new = (r[key_new][0] if isinstance(r[key_new], list) else r[key_new]) - \
                  (base[key_new][0] if isinstance(base[key_new], list) else base[key_new])
            s = 1 - new / old if old else float("nan")
            P5[f"{lab}: {name}"] = dict(old=old, new=new, share=s, label=label(s))
    e5o, e5n = load("e5_summary.json")["results"], load("e5_summary_v2.json")["results"]
    for name, f in (("VoI", lambda x: x["mean_VoI"][0][0]), ("beta_P intact", lambda x: x["betaP"][0][0]),
                    ("beta_P loop difference", lambda x: x["betaP"][0][2])):
        s = (f(e5o) - f(e5n)) / f(e5o); P5[f"S3: {name}"] = dict(old=f(e5o), new=f(e5n), share=s, label=label(s))
    v["P5"] = P5
save_json("c5_summary.json", dict(rows=rows, verdicts=v, missing=missing))
L = ["# C5 summary and list item 5 (auto-generated by experiments/c5_summary.py; rules in docs/RERUN.md, C5 and P5)\n"]
if missing:
    L.append(f"Missing `_v2` settings: {', '.join(missing)}. Rules not evaluated.")
else:
    L += ["| Setting | H1 ρ(Φ_orig) old → new [CI] | ρ(C), equal size, old → new [CI] | ρ(−K_H), equal size, old → new | log R driven old → new | eq log R new |",
          "|---|---|---|---|---|---|"]
    f = lambda x: f"{x[0]:+.2f} [{x[1]:+.2f}, {x[2]:+.2f}]"
    L += [f"| {lab} | {r['H1_old']:+.2f} → {f(r['H1_new'])} | {r['C_eq_old']:+.2f} → {f(r['C_eq_new'])} | {r['KH_eq_old']:+.2f} → {r['KH_eq_new']:+.2f} | "
          f"{r['logR_dr_old']:+.3f} → {r['logR_dr_new']:+.3f} | {r['logR_eq_new']:+.1e} |" for lab, r in rows.items()]
    L += ["", f"- W1 (C in all 9): {v['W1']}", f"- W2 (H4 fails in all 9): {v['W2']}", f"- W3 (control exact in all 9): {v['W3']}",
          f"- W4 (H1 supported in): {', '.join(v['W4']) or 'none'}", f"- W5 (D-test rule on corrected data): {v['W5']}", "",
          "List item 5: share s of a shift that came from the old exit check", "", "| Quantity | old | new | s | label |", "|---|---|---|---|---|"]
    L += [f"| {k} | {x['old']:+.3f} | {x['new']:+.3f} | {x['share']:+.2f} | {x['label']} |" for k, x in v["P5"].items()]
(RES / "c5_summary.md").write_text("\n".join(L) + "\n", encoding="utf-8"); print("\n".join(L))
