"""S1b - complexity term free of units: Phi_TC = P + C - 0.25*TC on the 9 S1 datasets. Rules in docs/S1b_unitfree.md.
No simulation. Same mask (>= 5 exits) and same cluster bootstrap over worlds as E3."""
import json, pickle
import numpy as np
from scipy.stats import spearmanr
from common import RES, save_json
from vlife.gaussian import total_correlation
from vlife.stats import cluster_bootstrap
from vlife.worlds import FAMILIES

SETTINGS = [("", "baseline"), ("_tau0.5", "tau 0.5"), ("_tau2", "tau 2"), ("_p0.01", "p_out 0.01"), ("_p0.2", "p_out 0.2"),
            ("_N5", "N 5"), ("_N7", "N 7"), ("_D2", "D-test r 2"), ("_D3", "D-test r 3")]
LAM = 0.25
FEATS = ("P", "C", "TC", "IAX")


def worlds(data):
    out = []
    for d in data:
        m = (d["ev_on"] >= 5) & (d["ev_eq"] >= 5)
        if m.sum() < 8:
            continue
        subs = [s for s, keep in zip(d["subsets"], m) if keep]
        f = {k: d["feat"][k][m] for k in ("P", "C", "KH", "IAX", "size")}
        f["TC"] = np.array([total_correlation(d["S"], s) for s in subs])
        out.append(dict(family=d["family"], y=np.log(d["V_on"][m]), f=f))
    return out


def rho(sc, y, size, stratify):
    groups = [np.ones(len(y), bool)] if not stratify else [size == k for k in np.unique(size)]
    r = [spearmanr(sc[g], y[g])[0] for g in groups if g.sum() >= 6 and np.ptp(sc[g]) > 0 and np.ptp(y[g]) > 0]
    return np.mean(r) if r else np.nan


def scores(f):
    return {"Phi_TC": f["P"] + f["C"] - LAM * f["TC"], "P+C": f["P"] + f["C"],
            "Phi_orig": f["P"] + f["C"] - LAM * f["KH"], "-TC": -f["TC"]}


def mean_rho(W, name, stratify):
    vals = np.array([rho(scores(w["f"])[name], w["y"], w["f"]["size"], stratify) for w in W])
    pt, lo, hi = cluster_bootstrap(len(W), lambda b: np.nanmean(vals[b]), 400)
    return [float(pt), float(lo), float(hi)]


def tc_coef(W):
    """Standardised within-world regression of log V on (P, C, TC, IAX). Returns TC coefficient and 95% CI."""
    Xd = [np.column_stack([w["f"][k] for k in FEATS]) for w in W]
    Xd = [x - x.mean(0) for x in Xd]; yd = [w["y"] - w["y"].mean() for w in W]
    scale = np.vstack(Xd).std(0); scale[scale == 0] = 1.0
    fit = lambda ids: np.linalg.lstsq(np.vstack([Xd[i] for i in ids]) / scale, np.concatenate([yd[i] for i in ids]), rcond=None)[0][2]
    pt, lo, hi = cluster_bootstrap(len(W), lambda b: fit(b), 300)
    return [float(pt), float(lo), float(hi)]


res = {}
for tag, label in SETTINGS:
    W = worlds(pickle.load(open(RES / f"e3_dataset{tag}.pkl", "rb")))
    r = {"label": label, "n_worlds": len(W)}
    for name in ("Phi_TC", "P+C", "Phi_orig", "-TC"):
        r[name] = mean_rho(W, name, False); r[name + " (equal size)"] = mean_rho(W, name, True)
    r["TC_coef"] = {fam: tc_coef([w for w in W if w["family"] == fam]) for fam in FAMILIES}
    res[tag or "_base"] = r
    print(label, "done", flush=True)

# ---- rules (fixed before the analysis, docs/S1b_unitfree.md)
R2 = {k: ("supported" if v["Phi_TC"][1] > 0 else "not supported") for k, v in res.items()}
d_keys = ["_base", "_D2", "_D3"]
R3 = "stable" if len({R2[k] for k in d_keys}) == 1 and abs(res["_D3"]["Phi_TC"][0] - res["_base"]["Phi_TC"][0]) < 0.1 else "not stable"
higher = sum(v["Phi_TC"][0] > v["P+C"][0] for v in res.values()); lower = sum(v["Phi_TC"][0] < v["P+C"][0] for v in res.values())
R4 = "helps" if higher >= 7 else ("hurts" if lower >= 7 else "no clear effect")
signs = [tuple(np.sign(v["TC_coef"][fam][0]) for fam in FAMILIES) for v in res.values()]
same = [len(set(s)) == 1 for s in signs]
R5 = ("stable" if sum(same) >= 8 else "not stable") + f" ({sum(same)} of 9 settings have one sign in all families; " \
     f"negative in {sum(1 for s, ok in zip(signs, same) if ok and s[0] < 0)}, positive in {sum(1 for s, ok in zip(signs, same) if ok and s[0] > 0)})"
verdicts = dict(R2=R2, R3=R3, R4=f"{R4} (Phi_TC higher than P+C in {higher} of 9, lower in {lower})", R5=R5)
save_json("s1b_unitfree.json", dict(results=res, verdicts=verdicts))

f2 = lambda v: f"{v[0]:+.2f} [{v[1]:+.2f}, {v[2]:+.2f}]"
L = ["# S1b results (auto-generated by experiments/s1b_unitfree.py; rules in docs/S1b_unitfree.md)\n",
     "Mean within-world Spearman rho with log V, 95% cluster-bootstrap CI.\n",
     "| setting | Phi_TC (R2) | P + C | Phi_orig | Phi_TC, equal size | -TC, equal size | TC coef eq / driven / modular |",
     "|---|---|---|---|---|---|---|"]
for k, v in res.items():
    c = " / ".join(f"{v['TC_coef'][fam][0]:+.3f}" for fam in FAMILIES)
    L.append(f"| {v['label']} | {f2(v['Phi_TC'])} {R2[k]} | {f2(v['P+C'])} | {f2(v['Phi_orig'])} | {f2(v['Phi_TC (equal size)'])} | {f2(v['-TC (equal size)'])} | {c} |")
L += ["", f"- R3 (stable when D changes): {R3}", f"- R4 (does TC help over P + C): {verdicts['R4']}", f"- R5 (TC sign): {R5}"]
(RES / "s1b_table.md").write_text("\n".join(L) + "\n", encoding="utf-8"); print("\n".join(L))
